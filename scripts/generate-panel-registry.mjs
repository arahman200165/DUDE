// Regenerates apps/web/src/app/core/registry/panel-definitions.ts from the distributed
// apps/web/src/app/**/<kind-id>.panel-manifest.ts files (DUDE_PRD.md Phase 30I).
//
// Panels are feature-owned: a manifest sits next to the component it renders, wherever that
// feature lives. The `.panel-manifest.ts` suffix is deliberately distinct from `.manifest.ts` so
// scripts/generate-tool-registry.mjs never picks a panel up as a tool.
//
// Usage: node scripts/generate-panel-registry.mjs

import { readdirSync, writeFileSync, readFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const APP_DIR = path.join(ROOT, 'apps/web/src/app');
const REGISTRY_FILE = path.join(ROOT, 'apps/web/src/app/core/registry/panel-definitions.ts');
const SUFFIX = '.panel-manifest.ts';

function findManifests(dir) {
  const results = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      results.push(...findManifests(full));
    } else if (entry.isFile() && entry.name.endsWith(SUFFIX)) {
      results.push(full);
    }
  }
  return results;
}

function toCamelCase(id) {
  return id
    .split('-')
    .map((word, i) => (i === 0 ? word : word[0].toUpperCase() + word.slice(1)))
    .join('');
}

const manifestPaths = findManifests(APP_DIR).sort((a, b) => a.localeCompare(b));

const seenIds = new Set();
const imports = [];
const identifiers = [];

for (const manifestPath of manifestPaths) {
  const id = path.basename(manifestPath, SUFFIX);
  if (!/^[a-z][a-z0-9]*(-[a-z0-9]+)*$/.test(id)) {
    throw new Error(`Panel manifest "${manifestPath}" must be named <kebab-case-kind-id>${SUFFIX}.`);
  }
  if (seenIds.has(id)) throw new Error(`Duplicate panel kind id found: ${id}`);
  seenIds.add(id);

  const identifier = `${toCamelCase(id)}Panel`;
  const relPath = path.relative(path.dirname(REGISTRY_FILE), manifestPath).replace(/\\/g, '/').replace(/\.ts$/, '');
  const relImport = relPath.startsWith('.') ? relPath : `./${relPath}`;

  imports.push(`import { panel as ${identifier} } from '${relImport}';`);
  identifiers.push(identifier);
}

const output = [
  '// AUTO-GENERATED by scripts/generate-panel-registry.mjs — do not edit by hand.',
  '// Run `npm run generate:registry` after adding, removing, or editing a <kind-id>.panel-manifest.ts',
  '// file. See ADDING_A_TOOL.md ("Adding a Home panel").',
  '',
  "import type { PanelDefinition } from '@dude/domain/shared/models/panel-definition.model';",
  ...imports,
  '',
  'export const PANEL_DEFINITIONS: readonly PanelDefinition[] = [',
  ...identifiers.map((id) => `  ${id},`),
  '];',
  '',
].join('\n');

const previous = existsSync(REGISTRY_FILE) ? readFileSync(REGISTRY_FILE, 'utf8') : '';
if (previous !== output) {
  writeFileSync(REGISTRY_FILE, output, 'utf8');
  console.log(`Regenerated panel-definitions.ts from ${manifestPaths.length} panel manifests.`);
} else {
  console.log(`panel-definitions.ts already up to date (${manifestPaths.length} panel manifests).`);
}
