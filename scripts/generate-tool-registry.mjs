// Regenerates src/app/core/registry/tool-definitions.ts from the distributed
// src/app/tools/**/<id>.manifest.ts files (DUDE_PRD.md Phase 22, Item 1).
//
// A new tool is added by creating one <id>.manifest.ts file next to its component —
// nothing else needs editing; re-run this script (wired as `pretest`/`prebuild`) to pick
// it up.
//
// Usage: node scripts/generate-tool-registry.mjs

import { readdirSync, statSync, writeFileSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const TOOLS_DIR = path.join(ROOT, 'src/app/tools');
const REGISTRY_FILE = path.join(ROOT, 'src/app/core/registry/tool-definitions.ts');

function findManifests(dir) {
  const results = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      results.push(...findManifests(full));
    } else if (entry.isFile() && entry.name.endsWith('.manifest.ts')) {
      results.push(full);
    }
  }
  return results;
}

function toCamelCase(id) {
  return id
    .split('-')
    .map((word, i) => (i === 0 ? word : word[0].toUpperCase() + word.slice(1)))
    .join('');
}

const manifestPaths = findManifests(TOOLS_DIR).sort((a, b) => a.localeCompare(b));

if (manifestPaths.length === 0) {
  throw new Error(`No *.manifest.ts files found under ${TOOLS_DIR}`);
}

const seenIds = new Set();
const imports = [];
const identifiers = [];

for (const manifestPath of manifestPaths) {
  const fileName = path.basename(manifestPath, '.manifest.ts');
  const folderName = path.basename(path.dirname(manifestPath));
  if (fileName !== folderName) {
    throw new Error(
      `Manifest file "${manifestPath}" does not match its folder name ("${fileName}" vs "${folderName}") — ` +
        'a tool\'s manifest must be named <id>.manifest.ts inside src/app/tools/<id>/.',
    );
  }
  const id = fileName;
  if (seenIds.has(id)) throw new Error(`Duplicate tool id/folder found: ${id}`);
  seenIds.add(id);

  const identifier = `${toCamelCase(id)}Manifest`;
  const relPath = path.relative(path.dirname(REGISTRY_FILE), manifestPath).replace(/\\/g, '/').replace(/\.ts$/, '');
  const relImport = relPath.startsWith('.') ? relPath : `./${relPath}`;

  imports.push(`import { manifest as ${identifier} } from '${relImport}';`);
  identifiers.push(identifier);
}

const header = [
  '// AUTO-GENERATED by scripts/generate-tool-registry.mjs — do not edit by hand.',
  '// Run `npm run generate:registry` after adding, removing, or editing a <id>.manifest.ts',
  '// file under src/app/tools/. See ADDING_A_TOOL.md.',
  '',
  "import type { ToolDefinition } from '../../shared/models/tool-definition.model';",
  ...imports,
  '',
  'export const TOOL_DEFINITIONS: readonly ToolDefinition[] = [',
  ...identifiers.map((id) => `  ${id},`),
  '];',
  '',
].join('\n');

const previous = readFileSync(REGISTRY_FILE, 'utf8');
if (previous !== header) {
  writeFileSync(REGISTRY_FILE, header, 'utf8');
  console.log(`Regenerated tool-definitions.ts from ${manifestPaths.length} manifests.`);
} else {
  console.log(`tool-definitions.ts already up to date (${manifestPaths.length} manifests).`);
}
