import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import ts from 'typescript';
import { ROOT, readManifests } from './tool-manifests.mjs';

const toolRoot = path.join(ROOT, 'apps/mobile/src/tools');
const output = path.join(ROOT, 'apps/mobile/src/registry/mobile-bindings.generated.ts');
const idsOutput = path.join(ROOT, 'packages/tool-registry/src/mobile-tool-ids.generated.ts');

/** Validate ownership without executing application source; imports remain statically visible. */
export function buildMobileBindings(entries, manifestIds) {
  const registered = new Set(manifestIds), seen = new Set();
  const sorted = [...entries].sort((a, b) => a.id.localeCompare(b.id));
  for (const { id, source, filename = `${id}/${id}.mobile-bindings.ts` } of sorted) {
    if (!registered.has(id)) throw new Error(`Unregistered mobile binding: ${id}`);
    if (seen.has(id)) throw new Error(`Duplicate mobile binding: ${id}`);
    seen.add(id);
    if (filename.replaceAll('\\', '/') !== `${id}/${id}.mobile-bindings.ts`) throw new Error(`Misplaced mobile binding: ${filename}`);
    const sf = ts.createSourceFile(filename, source, ts.ScriptTarget.Latest, true);
    const declarations = sf.statements.filter(statement => ts.isVariableStatement(statement)
      && statement.modifiers?.some(modifier => modifier.kind === ts.SyntaxKind.ExportKeyword))
      .flatMap(statement => [...statement.declarationList.declarations]);
    const bindingId = declarations.find(declaration => declaration.name.getText(sf) === 'bindingId')?.initializer;
    if (!bindingId || !ts.isStringLiteral(bindingId) || bindingId.text !== id) throw new Error(`Mismatched mobile binding ID: ${id}`);
    const binding = declarations.find(declaration => declaration.name.getText(sf) === 'binding')?.initializer;
    if (!binding) throw new Error(`Missing exported mobile binding: ${id}`);
    let lazy = 0;
    function visit(node) {
      if (ts.isCallExpression(node) && node.expression.kind === ts.SyntaxKind.ImportKeyword) {
        if (!node.arguments[0] || !ts.isStringLiteral(node.arguments[0])) throw new Error(`Nonliteral mobile UI import: ${id}`);
        lazy++;
      }
      ts.forEachChild(node, visit);
    }
    visit(binding);
    if (!lazy) throw new Error(`Missing lazy mobile UI import: ${id}`);
  }
  return '// AUTO-GENERATED by scripts/generate-mobile-bindings.mjs — do not edit.\n'
    + "import type { MobileBindingMap } from './mobile-binding';\n"
    + sorted.map(({ id }, index) => `import { binding as binding${index} } from '../tools/${id}/${id}.mobile-bindings';\n`).join('')
    + 'export const MOBILE_BINDINGS: MobileBindingMap = {\n'
    + sorted.map(({ id }, index) => `  '${id}': binding${index},\n`).join('') + '};\n';
}

/** Portable id list (no app imports) that web/desktop read to show "Also on Android". */
export function buildMobileToolIds(entries) {
  const ids = [...new Set(entries.map(({ id }) => id))].sort((a, b) => a.localeCompare(b));
  return '// AUTO-GENERATED by scripts/generate-mobile-bindings.mjs — generated — do not edit.\n'
    + '/** Tool IDs that have an executable Android binding. */\n'
    + `export const MOBILE_TOOL_IDS: readonly string[] = [${ids.map(id => `\n  '${id}',`).join('')}${ids.length ? '\n' : ''}];\n`;
}

/** Binding files under `dir`; directories starting with `_` (spikes, scratch) are never discovered. */
export function files(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true }).flatMap(entry => {
    if (entry.name.startsWith('_')) return [];
    const file = path.join(dir, entry.name);
    return entry.isDirectory() ? files(file) : entry.name.endsWith('.mobile-bindings.ts') ? [file] : [];
  });
}
export function run({ root = toolRoot, bindingsOutput = output, toolIdsOutput = idsOutput, manifestIds, check = false }) {
  const entries = files(root).map(file => ({
    id: path.basename(file).replace(/\.mobile-bindings\.ts$/, ''),
    filename: path.relative(root, file), source: readFileSync(file, 'utf8'),
  }));
  const generated = buildMobileBindings(entries, manifestIds);
  const ids = buildMobileToolIds(entries);
  if (check) {
    if (!existsSync(bindingsOutput) || readFileSync(bindingsOutput, 'utf8') !== generated
      || !existsSync(toolIdsOutput) || readFileSync(toolIdsOutput, 'utf8') !== ids) throw new Error('Mobile bindings are stale: run npm run generate:registry.');
    return 'generate-mobile-bindings: up to date';
  }
  mkdirSync(path.dirname(bindingsOutput), { recursive: true });
  mkdirSync(path.dirname(toolIdsOutput), { recursive: true });
  writeFileSync(bindingsOutput, generated);
  writeFileSync(toolIdsOutput, ids);
  return `Generated ${entries.length} mobile UI bindings.`;
}
function main() {
  console.log(run({ manifestIds: readManifests().map(({ metadata }) => metadata.id), check: process.argv.includes('--check') }));
}
if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  try { main(); } catch (error) { console.error(error.message); process.exitCode = 1; }
}
